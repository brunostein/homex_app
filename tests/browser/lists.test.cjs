const { test } = require('node:test');
const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const fs = require('node:fs/promises');
process.loadEnvFile('.env');

test('lists: responsive cards, search, sharing filters, inventory, updates and safe deletion', { timeout: 120000 }, async () => {
  const base = process.env.EXPO_PUBLIC_API_URL;
  assert.ok(base && ['localhost', '127.0.0.1', '[::1]'].includes(new URL(base).hostname), 'Use a local API.');
  const browser = await chromium.launch({ ...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH } : {}) });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  let token; let userToken;
  const users = [];
  const email = `lists-${Date.now()}@homex.local`;
  const password = 'lists-test-password';
  async function api(path, method = 'GET', data) {
    const response = await fetch(`${base}${path}`, { method, headers: { 'Content-Type': 'application/json', ...(token ? { Authorization: `Bearer ${token}` } : {}), ...(userToken ? { 'X-Homex-User-Token': userToken } : {}) }, ...(data ? { body: JSON.stringify(data) } : {}) });
    const result = await response.json();
    assert.equal(result.success, true, result.msg);
    return result.data;
  }
  const button = name => page.getByRole('button', { name, exact: true });
  const searchHomes = () => page.getByRole('textbox', { name: 'Buscar casas', exact: true });
  const searchItems = () => page.getByRole('textbox', { name: 'Buscar no inventário', exact: true });
  const noOverflow = async () => assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  async function preview(name) {
    if (!process.env.HOMEX_PREVIEW_DIR) return;
    await fs.mkdir(process.env.HOMEX_PREVIEW_DIR, { recursive: true });
    await page.screenshot({ path: `${process.env.HOMEX_PREVIEW_DIR}/${name}.png`, fullPage: true });
  }
  try {
    token = (await api('/accounts/signin', 'POST', { username: process.env.EXPO_PUBLIC_API_USER, password: process.env.EXPO_PUBLIC_API_PASSWORD })).access_token;
    users.push(await api('/homex/users/create', 'POST', { fullName: 'Marina', email, password }));
    users.push(await api('/homex/users/create', 'POST', { fullName: 'Pessoa convidada', email: `guest-${email}`, password }));
    userToken = (await api('/homex/users/signin', 'POST', { email, password })).user_token;
    await page.goto(process.env.HOMEX_WEB_URL || 'http://127.0.0.1:8092');
    await page.getByRole('textbox', { name: 'Email', exact: true }).fill(email);
    await page.getByLabel('Senha', { exact: true }).fill(password);
    await button('Entrar').click();
    await page.getByText('Sua organização começa aqui.', { exact: true }).waitFor();
    const home = await api('/homex/homes/create', 'POST', { name: 'Casa do Sol', descr: 'Nosso cantinho, organizado com carinho.', user_id: users[0].id });
    const apartment = await api('/homex/homes/create', 'POST', { name: 'Apartamento Centro', descr: 'Um espaço para a rotina da cidade.', user_id: users[0].id });
    const shared = await api('/homex/homes/create', 'POST', { name: 'Casa da família', descr: 'Todo mundo por perto, tudo no seu lugar.', user_id: users[1].id });
    const ownToken = userToken;
    userToken = (await api('/homex/users/signin', 'POST', { email: users[1].email, password })).user_token;
    await api(`/homex/homes/share/${shared.id}`, 'POST', { email });
    userToken = ownToken;
    const category = await api('/homex/categories/create', 'POST', { name: 'Cozinha', home_id: home.id });
    await api('/homex/categories/create', 'POST', { name: 'Lavanderia', home_id: home.id });
    const coffee = await api('/homex/items/create', 'POST', { name: 'Café', amount: 2, category_id: category.id });
    const rice = await api('/homex/items/create', 'POST', { name: 'Arroz integral', amount: 3, category_id: category.id });
    const missing = await api('/homex/items/create', 'POST', { name: 'Feijão', amount: 0, category_id: category.id });
    await button('Atualizar lista').click();
    await page.getByTestId(`home-card-${home.id}`).waitFor();
    await noOverflow();
    await preview('casas-desktop');
    const homeBox = await page.getByTestId(`home-card-${home.id}`).boundingBox();
    const secondBox = await page.getByTestId(`home-card-${apartment.id}`).boundingBox();
    assert.ok(Math.abs(homeBox.y - secondBox.y) < 2, 'Desktop cards should form a grid.');
    await searchHomes().fill('FAMILIA');
    assert.equal(await page.getByTestId(`home-card-${shared.id}`).count(), 1);
    assert.equal(await page.getByTestId(`home-card-${home.id}`).count(), 0);
    await button('Limpar busca').click();
    await button('Compartilhadas').click();
    assert.equal(await page.getByRole('button', { name: 'Abrir casa', exact: true }).count(), 1);
    assert.equal(await page.getByTestId(`home-card-${shared.id}`).getByRole('button', { name: /Editar|Opções/ }).count(), 0);
    await button('Minhas').click();
    assert.equal(await page.getByRole('button', { name: 'Abrir casa', exact: true }).count(), 2);
    await searchHomes().fill('inexistente');
    await page.getByText('Nenhuma casa por aqui.', { exact: true }).waitFor();
    await button('Ver todas as casas').click();
    await page.setViewportSize({ width: 390, height: 844 });
    await noOverflow(); await preview('casas-celular');
    await page.getByTestId(`home-card-${shared.id}`).getByRole('button', { name: 'Abrir casa', exact: true }).click();
    await button('Inventário da casa').click();
    await page.getByText('Acesso de leitura', { exact: true }).waitFor();
    assert.equal(await button('Nova categoria').count(), 0);
    await button('Voltar').click(); await button('Voltar').click();
    await page.getByTestId(`home-card-${home.id}`).getByRole('button', { name: 'Abrir casa', exact: true }).click();
    await button('Inventário da casa').click();
    await page.getByTestId(`item-${coffee.id}`).waitFor();
    await noOverflow(); await preview('inventario-celular');
    await page.setViewportSize({ width: 1440, height: 1000 });
    await noOverflow(); await preview('inventario-desktop');
    await searchItems().fill('cafe');
    assert.equal(await page.getByTestId(`item-${coffee.id}`).count(), 1);
    assert.equal(await page.getByTestId(`item-${rice.id}`).count(), 0);
    await button('Limpar busca').click();
    await button('Em falta').click();
    await page.getByTestId(`item-${missing.id}`).waitFor();
    assert.equal(await button('Diminuir Feijão').isDisabled(), true);
    assert.equal(await page.getByTestId(`item-${coffee.id}`).count(), 0);
    await button('Todos os itens').click();
    await button('Recolher categoria Cozinha').click();
    assert.equal(await page.getByTestId(`item-${coffee.id}`).count(), 0);
    await button('Expandir categoria Cozinha').click();
    await Promise.all([page.waitForResponse(response => response.url().includes(`/items/update/${coffee.id}`)), button('Aumentar Café').click()]);
    assert.equal((await api(`/homex/items/get/${coffee.id}`)).amount, 3);
    await page.route(`**/homex/items/update/${coffee.id}`, route => route.abort());
    await button('Aumentar Café').click();
    await page.getByRole('alert').filter({ hasText: 'Não foi possível atualizar a quantidade.' }).waitFor();
    assert.equal((await api(`/homex/items/get/${coffee.id}`)).amount, 3);
    await page.unroute(`**/homex/items/update/${coffee.id}`);
    await button('Remover Feijão').click();
    await button('Cancelar').click();
    assert.equal(await page.getByTestId(`item-${missing.id}`).count(), 1);
    await button('Remover Feijão').click(); await button('Remover').click();
    await page.getByTestId(`item-${missing.id}`).waitFor({ state: 'detached' });
    await button('Em falta').click();
    await page.getByText('Tudo em dia por aqui.', { exact: true }).waitFor();
    await button('Ver todos os itens').click();
    await button('Opções de Lavanderia').click();
    await page.getByRole('menuitem', { name: 'Remover', exact: true }).click();
    await button('Remover').click();
    await page.getByRole('button', { name: 'Recolher categoria Lavanderia', exact: true }).waitFor({ state: 'detached' });
    await button('Voltar').click(); await button('Voltar').click();
    await button('Opções de Apartamento Centro').click();
    await page.getByRole('menuitem', { name: 'Remover', exact: true }).click();
    await button('Remover').click();
    await page.getByTestId(`home-card-${apartment.id}`).waitFor({ state: 'detached' });
    assert.deepEqual(errors, []);
  } catch (error) {
    await preview('falha');
    console.error(await page.locator('body').innerText());
    throw error;
  } finally {
    for (const user of users) await api(`/homex/users/remove/${user.id}`, 'DELETE');
    await browser.close();
  }
});
